package projector

import (
	"fmt"
	"strings"
)

func GenerateEvaluator(ir SemanticIR, irDigest, sourceDigest string) []byte {
	var builder strings.Builder
	builder.WriteString("// Code generated by gooo. DO NOT EDIT.\n\n")
	builder.WriteString("package generated\n\n")
	fmt.Fprintf(&builder, "const SourceDigest = %q\n", sourceDigest)
	fmt.Fprintf(&builder, "const SemanticIRDigest = %q\n", irDigest)
	fmt.Fprintf(&builder, "const ResolutionPrecedence = %q\n", "REFUTED>UNKNOWN>CLOSED")
	fmt.Fprintf(&builder, "const RuntimeApplyAuthority = %d\n", 0)
	fmt.Fprintf(&builder, "const MetaActivityCount = %d\n\n", ir.Total)
	builder.WriteString("type Activity struct {\n")
	builder.WriteString("\tID string\n\tClaimID string\n\tOperationID string\n\tProofChoice string\n\tIndicatorClass string\n}\n\n")
	builder.WriteString("var Activities = []Activity{\n")
	for _, activity := range ir.Activities {
		fmt.Fprintf(&builder, "\t{ID: %q, ClaimID: %q, OperationID: %q, ProofChoice: %q, IndicatorClass: %q},\n", activity.ID, activity.ClaimID, activity.OperationID, activity.ProofChoice, activity.IndicatorClass)
	}
	builder.WriteString("}\n")
	return []byte(builder.String())
}
